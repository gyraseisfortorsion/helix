def test_public_blood_demo_is_real_separate_idempotent_and_explained_in_chat(client):
    session, headers = demo_session(client)
    response = client.post("/api/demo/methylation-report", headers=headers)
    assert response.status_code == 200
    profile = response.json()["profile"]
    assert profile["public_dataset_key"] == "GSM1009666"
    assert profile["id"] not in {p["id"] for p in session["profiles"]}
    assert (
        client.post("/api/demo/methylation-report", headers=headers).json()["profile"]["id"] == profile["id"]
    )
    report = client.get(f"/api/profiles/{profile['id']}/methylation", headers=headers).json()
    sample = report["samples"][0]
    assert sample["age_report"]["status"] == "ready"
    assert sample["age_report"]["estimate_years"] == pytest.approx(25.763743, abs=1e-6)
    assert sample["age_report"]["age_at_collection"] == 21
    assert "raw control probes" in sample["age_report"]["qc_scope"]
    assert report["comparisons"] == []  # No invented collection date or pair.
    job = client.post(
        "/api/messages",
        headers=headers,
        json={"profile_id": profile["id"], "question": "Explain my methylation age report"},
    ).json()["job_id"]
    answer = wait_job(client, job, headers)["result"]["answer"]
    assert "25.8 years" in answer["response"]
    assert "not a health rating" in answer["response"]
    assert (
        client.get(f"/api/profiles/{session['profiles'][0]['id']}/methylation", headers=headers).json()[
            "samples"
        ]
        == []
    )


def test_molecular_explanation_uses_actual_differences_and_flags_irrelevant_context():
    report = explain_prediction(
        {
            "provider": "alphagenome",
            "variant": {"rsid": "rs143383", "ref": "G", "alt": "A"},
            "context_name": "HepG2",
            "tracks": [
                {
                    "modality": "ATAC",
                    "name": "test",
                    "x": [10, 20],
                    "reference": [1, 2],
                    "alternate": [1.25, 1.5],
                    "units": "test units",
                }
            ],
        }
    )
    finding = report["findings"][0]
    assert finding["largest_absolute_difference"] == 0.5
    assert finding["largest_difference_position"] == 20
    assert finding["mean_absolute_difference"] == 0.375
    assert "cannot explain knee pain" in report["context_note"]
    assert "DNA accessibility" in finding["meaning"]
    assert "not proof" in report["published_context"]
    assert "significance" in report["metric_scope"]
